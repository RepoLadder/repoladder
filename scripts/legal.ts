// Legal files: the copyright holder (one constant), NOTICE and THIRD-PARTY-NOTICES.txt, for the repo root and plugin/.
// Run `npm run legal` after changing the holder or a bundled dependency; test/legal.test.ts fails on drift.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ELK_URL } from "../src/viewer/elkload.ts";

const repo = resolve(fileURLToPath(new URL("..", import.meta.url)));

/** The single place the copyright holder lives. */
export const COPYRIGHT_HOLDER = "RepoLadder";
export const COPYRIGHT_YEAR = 2026;

/** Packages the bundles leave external (installed on first use); keep in step with scripts/bundle.ts. */
export const EXTERNALS = ["typescript", "@terrastruct/d2"];

interface Entry { license: string; licenseFile: string }

/** Bundled third-party code and where its full license text lives. esbuild's runtime helpers are inlined in every bundle. */
export const THIRD_PARTY: Record<string, Entry> = {
  "@repoladder/brand": { license: "MIT", licenseFile: "node_modules/@repoladder/brand/LICENSE" },
  esbuild: { license: "MIT", licenseFile: "node_modules/esbuild/LICENSE.md" },
  zod: { license: "MIT", licenseFile: "node_modules/zod/LICENSE" },
};

/** Packages that appear in the bundles' esbuild inputs (same entry points and externals as the real builds). */
export async function bundledPackages(): Promise<string[]> {
  const found = new Set<string>();
  const run = async (entries: string[], platform: "node" | "browser") => {
    const r = await build({
      entryPoints: entries.map((e) => resolve(repo, e)),
      bundle: true,
      platform,
      format: "esm",
      write: false,
      outdir: resolve(repo, ".legal-unused"),
      metafile: true,
      logLevel: "silent",
      external: EXTERNALS,
      loader: { ".woff2": "dataurl", ".woff": "dataurl", ".css": "text", ".svg": "text" },
    });
    for (const k of Object.keys(r.metafile.inputs)) {
      const m = /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(k);
      if (m) found.add(m[1]);
    }
  };
  await run(["src/cli.ts", "src/lib.ts"], "node");
  await run(["src/viewer/main.ts", "src/viewer/boot.ts"], "browser");
  return [...found].sort();
}

/** The license text; for the brand package only the MIT part (its logos are not bundled and carry other terms). */
function licenseText(e: Entry): string {
  const t = readFileSync(resolve(repo, e.licenseFile), "utf8");
  const cut = t.indexOf("Logos and name.");
  return (cut >= 0 ? t.slice(0, cut) : t).trim();
}

const rule = "=".repeat(72);

/** The text of THIRD-PARTY-NOTICES.txt. */
export async function generateNotices(): Promise<string> {
  const bundled = await bundledPackages();
  for (const p of bundled) if (!THIRD_PARTY[p]) throw new Error(`LEGAL_FAILED ${p} is bundled but has no entry in THIRD_PARTY (scripts/legal.ts)`);
  const names = [...new Set([...bundled, "esbuild"])].sort();
  const elk = /elkjs@([^/]+)\//.exec(ELK_URL)?.[1] ?? "";
  const out: string[] = [
    "Third-party notices for RepoLadder",
    "",
    "RepoLadder itself is licensed under the Apache License 2.0 (see LICENSE).",
    "It bundles the code below, whose full license texts follow, and credits the",
    "software it loads or installs but does not bundle.",
    "",
    rule,
    "Bundled code",
    rule,
  ];
  for (const n of names) {
    const e = THIRD_PARTY[n];
    out.push("", `--- ${n} (${e.license}) ---`, "", licenseText(e));
  }
  out.push(
    "",
    rule,
    "Credits (not bundled)",
    rule,
    "",
    "--- typescript ---",
    "License: Apache-2.0. Copyright Microsoft Corporation.",
    "Installed unmodified on first use; not bundled. https://github.com/microsoft/TypeScript",
    "",
    "--- @terrastruct/d2 ---",
    "License: MPL-2.0.",
    "Installed unmodified on first use; not bundled. Source: https://github.com/terrastruct/d2",
    "",
    "--- elkjs ---",
    "License: EPL-2.0 OR GPL-3.0-or-later, used under EPL-2.0.",
    `Not bundled: the viewer loads elkjs@${elk} from cdn.jsdelivr.net at runtime. Source: https://github.com/kieler/elkjs`,
    "",
    "--- Geist and Geist Mono ---",
    "License: SIL Open Font License 1.1. Copyright 2024 The Geist Project Authors.",
    "Embedded as subsets in diagram pages. Full text in LICENSE-Geist.txt.",
    "",
  );
  return out.join("\n");
}

/** The text of NOTICE. */
export function noticeText(): string {
  return [
    "RepoLadder",
    `Copyright ${COPYRIGHT_YEAR} ${COPYRIGHT_HOLDER}`,
    "",
    "Diagram pages made by RepoLadder embed subsets of Geist and Geist Mono.",
    "Copyright 2024 The Geist Project Authors, under the SIL Open Font License 1.1 (see LICENSE-Geist.txt).",
    "The subset files are in src/viewer/fonts/ and are generated by scripts/fonts.ts.",
    "",
    "Third-party software is credited in THIRD-PARTY-NOTICES.txt.",
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const notices = await generateNotices();
  for (const dir of ["", "plugin/"]) {
    writeFileSync(resolve(repo, `${dir}NOTICE`), noticeText());
    writeFileSync(resolve(repo, `${dir}THIRD-PARTY-NOTICES.txt`), notices);
  }
  console.log("LEGAL_OK");
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  try { await main(); }
  catch (e) {
    console.error(e instanceof Error ? e.message : String(e));
    process.exit(1);
  }
}
