// The owner's RepoLadder mark, as the page's one favicon and the header's inline mark. The sources are
// mark.svg and mark-dark.svg (byte copies of @repoladder/brand's logos); `node scripts/mark.ts` regenerates the two
// constants at the bottom. No Node imports: this file is bundled into the plugin.

/** Strips everything a favicon or inline mark doesn't need, deterministically. The page keeps exactly one <title>. */
export function minifySvg(src: string): string {
  return src
    .replace(/<\?xml[\s\S]*?\?>/g, "")
    .replace(/<!DOCTYPE[\s\S]*?>/gi, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<title[\s\S]*?<\/title>/g, "")
    .replace(/<metadata[\s\S]*?<\/metadata>/g, "")
    .replace(/<(?:sodipodi|inkscape):[^>]*?(?:\/>|>[\s\S]*?<\/(?:sodipodi|inkscape):[\w-]+>)/g, "")
    .replace(/\s(?:sodipodi|inkscape|xmlns:sodipodi|xmlns:inkscape|xmlns:xlink|data-name)(?::[\w-]+)?\s*=\s*(?:"[^"]*"|'[^']*')/g, "")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim()
    .replace(/"/g, "'");
}

/** Prefixes every id and its url(#id) / href='#id' references, so two inlined marks never collide. */
export function prefixIds(svg: string, p: string): string {
  return svg
    .replace(/\bid='([^']*)'/g, (_m, id: string) => `id='${p}${id}'`)
    .replace(/url\(#([^)]*)\)/g, (_m, id: string) => `url(#${p}${id})`)
    .replace(/href='#([^']*)'/g, (_m, id: string) => `href='#${p}${id}'`);
}

const split = (svg: string) => {
  const s = minifySvg(svg);
  const open = s.match(/^<svg\b[^>]*>/)![0];
  return { open, inner: s.slice(open.length, s.lastIndexOf("</svg>")) };
};

/** One SVG for the favicon: the light mark, plus the dark one swapped in by prefers-color-scheme when given. */
export function composeMark(light: string, dark?: string): string {
  if (dark === undefined) return minifySvg(light);
  const l = split(light), d = split(dark);
  return minifySvg(`${l.open}<style>.d{display:none}@media (prefers-color-scheme:dark){.l{display:none}.d{display:inline}}</style><g class='l'>${l.inner}</g><g class='d'>${prefixIds(d.inner, "d-")}</g></svg>`);
}

/** Percent-encoded data URI (not base64): `%` first so later escapes aren't doubled. */
export function svgDataUri(svg: string): string {
  return "data:image/svg+xml," + svg.replace(/%/g, "%25").replace(/#/g, "%23").replace(/</g, "%3C").replace(/>/g, "%3E").replace(/"/g, "%22");
}

/** Both marks inline for the header; styles.css shows the one that matches the theme. */
export function headerMark(light: string, dark: string): string {
  const one = (svg: string, p: string, cls: string) =>
    prefixIds(minifySvg(svg), p).replace(/^<svg\b/, `<svg class='${cls}' width='24' height='24' aria-hidden='true' focusable='false'`);
  return one(light, "rlm-l-", "mk mk-l") + one(dark, "rlm-d-", "mk mk-d");
}

